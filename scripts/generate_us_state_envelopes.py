"""Regenerate ``trid3nt_server/tools/fetchers/us_state_envelopes.py`` from the Census cartographic boundary file.

Each state's envelope is the bounding box of its polygons, rounded outward to a thousandth of a degree, so it
always holds the boundary it was read from. A state whose polygons straddle the antimeridian (Alaska's Aleutians)
gets a wrapping envelope, west greater than east. Run: ``venvs/agent/bin/python scripts/generate_us_state_envelopes.py
[--zip <downloaded cb_<vintage>_us_state_500k.zip>]``; without ``--zip`` the file is downloaded.
"""

from __future__ import annotations

import argparse
import math
import tempfile
import urllib.request
from pathlib import Path

import pyogrio
from shapely.geometry import MultiPolygon

VINTAGE = 2025
URL = f"https://www2.census.gov/geo/tiger/GENZ{VINTAGE}/shp/cb_{VINTAGE}_us_state_500k.zip"
OUT = Path(__file__).resolve().parents[1] / "trid3nt_server" / "tools" / "fetchers" / "us_state_envelopes.py"

#: The states outside the conterminous United States; everything else in the file, DC included, is in it.
_NOT_CONTERMINOUS = {"AK", "HI", "PR", "VI", "GU", "AS", "MP"}


def _down(value: float) -> float:
    return math.floor(value * 1000.0) / 1000.0


def _up(value: float) -> float:
    return math.ceil(value * 1000.0) / 1000.0


def _envelope(geometry) -> tuple[float, float, float, float]:
    parts = list(geometry.geoms) if isinstance(geometry, MultiPolygon) else [geometry]
    bounds = [part.bounds for part in parts]
    south = min(b[1] for b in bounds)
    north = max(b[3] for b in bounds)
    west, east = min(b[0] for b in bounds), max(b[2] for b in bounds)
    if east - west <= 180.0:
        return (_down(west), _down(south), _up(east), _up(north))
    # Across the antimeridian: the eastern-hemisphere parts start the box, the western ones end it.
    west = min(b[0] for b in bounds if b[0] > 0.0)
    east = max(b[2] for b in bounds if b[2] < 0.0)
    return (_down(west), _down(south), _up(east), _up(north))


def _table(zip_path: Path) -> tuple[dict[str, tuple[float, ...]], tuple[float, ...]]:
    frame = pyogrio.read_dataframe(f"/vsizip/{zip_path}/cb_{VINTAGE}_us_state_500k.shp")
    envelopes = {str(row.STUSPS): _envelope(row.geometry)
                 for row in frame.itertuples() if row.geometry is not None}
    conterminous = [env for code, env in envelopes.items() if code not in _NOT_CONTERMINOUS]
    land = (min(e[0] for e in conterminous), min(e[1] for e in conterminous),
            max(e[2] for e in conterminous), max(e[3] for e in conterminous))
    return dict(sorted(envelopes.items())), land


def _render(envelopes: dict[str, tuple[float, ...]], land: tuple[float, ...]) -> str:
    rows = "\n".join(f'    "{code}": {env!r},' for code, env in envelopes.items())
    return (
        '"""The envelope of every US state and territory, and of the conterminous United States.\n\n'
        f"Generated by scripts/generate_us_state_envelopes.py from the Census Bureau's {VINTAGE} cartographic\n"
        "boundary file named by SOURCE; never edited by hand. Degrees on the file's NAD83 frame, rounded outward\n"
        "to 0.001 so an envelope holds its boundary; west greater than east is an envelope across the antimeridian.\n"
        '"""\n\n'
        '__all__ = ["CONUS_LAND", "SOURCE", "STATE_ENVELOPES", "VINTAGE"]\n\n'
        f"SOURCE = {URL!r}\n"
        f"VINTAGE = {VINTAGE}\n\n"
        "#: Postal code -> (west, south, east, north).\n"
        f"STATE_ENVELOPES: dict[str, tuple[float, float, float, float]] = {{\n{rows}\n}}\n\n"
        "#: The 48 conterminous states and DC.\n"
        f"CONUS_LAND: tuple[float, float, float, float] = {land!r}\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--zip", type=Path, help="an already downloaded cb_<vintage>_us_state_500k.zip")
    args = parser.parse_args()
    if args.zip is not None:
        envelopes, land = _table(args.zip.resolve())
    else:
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / Path(URL).name
            urllib.request.urlretrieve(URL, path)
            envelopes, land = _table(path)
    OUT.write_text(_render(envelopes, land), encoding="utf-8")
    print(f"{OUT}: {len(envelopes)} envelopes, CONUS_LAND {land}")


if __name__ == "__main__":
    main()
